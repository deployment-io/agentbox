// TestYarnLockIsBerry checks the lockfile sniff on its own, including a
// lockfile long enough that the marker is only reachable within the bounded
// read (a real Berry lockfile is megabytes; only its head is scanned).
func TestYarnLockIsBerry(t *testing.T) {
	cases := []struct {
		name    string
		content string
		want    bool
	}{
		{"berry", berryLock, true},
		{"classic", classicLock, false},
		{"empty", "", false},
		{"berry with a long entry after the marker", berryLock + strings.Repeat("# padding\n", 4096), true},
		{"__metadata only as an indented value", "deps:\n  __metadata: 8\n", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			writeFiles(t, dir, map[string]string{"yarn.lock": tc.content})
			if got := yarnLockIsBerry(dir); got != tc.want {
				t.Errorf("yarnLockIsBerry() = %v, want %v", got, tc.want)
			}
		})
	}

	t.Run("no yarn.lock", func(t *testing.T) {
		if yarnLockIsBerry(t.TempDir()) {
			t.Error("yarnLockIsBerry() = true with no lockfile, want false")
		}
	})
}

func TestMetadata(t *testing.T) {
	d := &detector{}
	if d.Name() != "node" {
		t.Errorf("Name() = %q, want \"node\"", d.Name())
	}
	if err := d.EnsureToolchain(context.Background()); err != nil {
		t.Errorf("EnsureToolchain() = %v, want nil (Node is baseline)", err)
	}
	if len(d.AllowedHosts()) == 0 {
		t.Error("AllowedHosts() should be non-empty")
	}
	if len(d.VerifyHosts()) == 0 {
		t.Error("VerifyHosts() should be non-empty")
	}
	if err := d.Finalize("/work", nil); err != nil {
		t.Errorf("Finalize() = %v, want nil", err)
	}
}

// TestEnvRedirectsToSharedCache verifies that when cacheDir is set, each
// supported package manager's cache env var points into a subdirectory
// of the shared cache — moving big tarball downloads off the
// memory-backed /home/agent tmpfs.
func TestEnvRedirectsToSharedCache(t *testing.T) {
	d := &detector{}
	got := d.Env("/cache", nil)
	want := []string{
		"YARN_CACHE_FOLDER=/cache/yarn",
		"YARN_GLOBAL_FOLDER=/cache/yarn-berry",
		"npm_config_cache=/cache/npm",
		"npm_config_store_dir=/cache/pnpm",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Env(\"/cache\", nil) = %v, want %v", got, want)
	}
}

